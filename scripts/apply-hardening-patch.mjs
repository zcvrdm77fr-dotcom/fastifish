import fs from 'node:fs';

function read(file) {
  return fs.readFileSync(file, 'utf8');
}

function write(file, content) {
  fs.writeFileSync(file, content);
  console.log(`patched ${file}`);
}

function replaceExact(file, search, replacement, label = search.slice(0, 60)) {
  const source = read(file);
  if (!source.includes(search)) throw new Error(`${file}: missing expected text for ${label}`);
  write(file, source.replace(search, replacement));
}

function replaceRegex(file, pattern, replacement, label) {
  const source = read(file);
  if (!pattern.test(source)) throw new Error(`${file}: missing expected pattern for ${label}`);
  write(file, source.replace(pattern, replacement));
}

